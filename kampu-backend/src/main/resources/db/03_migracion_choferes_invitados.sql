CREATE TABLE CHOFERES (
    chofer_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo VARCHAR2(150) NOT NULL,
    numero_licencia VARCHAR2(20) NOT NULL UNIQUE,
    categoria_licencia VARCHAR2(10) NOT NULL,
    telefono VARCHAR2(20),
    transporte_id NUMBER,
    estado VARCHAR2(20) DEFAULT 'ACTIVO',
    CONSTRAINT chk_chofer_categoria CHECK (categoria_licencia IN ('A-IIa', 'A-IIb', 'A-IIIa', 'A-IIIb', 'A-IIIc')),
    CONSTRAINT chk_chofer_estado CHECK (estado IN ('ACTIVO', 'INACTIVO')),
    CONSTRAINT fk_chofer_transporte FOREIGN KEY (transporte_id) REFERENCES TRANSPORTE(transporte_id)
);

ALTER TABLE SALIDAS_PROGRAMADAS ADD (
    chofer_id NUMBER,
    CONSTRAINT chk_salida_chofer CHECK (chofer_id IS NULL OR transporte_id IS NOT NULL),
    CONSTRAINT fk_salida_chofer FOREIGN KEY (chofer_id) REFERENCES CHOFERES(chofer_id)
);

ALTER TABLE RESERVAS MODIFY (cliente_id NULL);

ALTER TABLE RESERVAS ADD (
    contacto_nombre VARCHAR2(150),
    contacto_email VARCHAR2(100),
    contacto_telefono VARCHAR2(20),
    boleta_enviada_en TIMESTAMP,
    CONSTRAINT chk_res_cliente_o_contacto CHECK (
        cliente_id IS NOT NULL
        OR (contacto_nombre IS NOT NULL AND contacto_email IS NOT NULL AND contacto_telefono IS NOT NULL))
);

