-- =====================================================================
-- 4. COMERCIAL: SALIDAS, RESERVAS (cabecera), DETALLE, PASAJEROS, PAGOS
-- =====================================================================
CREATE TABLE SALIDAS_PROGRAMADAS (
    salida_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paquete_id        NUMBER NOT NULL,
    fecha_inicio      DATE   NOT NULL,
    fecha_fin         DATE   NOT NULL,      -- si va NULL, el trigger la calcula con PAQUETES_TOUR.dias
    cupos_maximos     NUMBER(3) NOT NULL,
    cupos_disponibles NUMBER(3) NOT NULL,   -- lo asignan los triggers
    guia_id           NUMBER,
    estado            VARCHAR2(20) DEFAULT 'PROGRAMADA',
    CONSTRAINT chk_salida_fechas CHECK (fecha_fin >= fecha_inicio),
    CONSTRAINT chk_salida_cupos  CHECK (cupos_maximos > 0 AND cupos_disponibles >= 0
                                        AND cupos_disponibles <= cupos_maximos),
    CONSTRAINT chk_salida_estado CHECK (estado IN ('PROGRAMADA', 'CONFIRMADA', 'COMPLETADA', 'CANCELADA')),
    CONSTRAINT fk_salida_paquete FOREIGN KEY (paquete_id) REFERENCES PAQUETES_TOUR(paquete_id),
    CONSTRAINT fk_salida_guia    FOREIGN KEY (guia_id)    REFERENCES GUIAS(guia_id)
)
STORAGE (INITIAL 640K NEXT 640K MINEXTENTS 3);

CREATE TABLE RESERVAS (
    reserva_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id         NUMBER,
    fecha_reserva      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    monto_total        NUMBER(10,2) DEFAULT 0 NOT NULL,   -- = SUM(DETALLE_RESERVA.subtotal), por trigger
    monto_pagado       NUMBER(10,2) DEFAULT 0 NOT NULL,
    estado_reserva     VARCHAR2(20) DEFAULT 'PENDIENTE',
    estado_pago        VARCHAR2(20) DEFAULT 'PENDIENTE',
    observaciones      VARCHAR2(200),
    forma_reembolso    VARCHAR2(50),
    usuario_anula_id   NUMBER,
    contacto_nombre    VARCHAR2(150),
    contacto_email     VARCHAR2(100),
    contacto_telefono  VARCHAR2(20),
    boleta_enviada_en  TIMESTAMP,
    CONSTRAINT chk_res_cliente_o_contacto CHECK (
        cliente_id IS NOT NULL
        OR (contacto_nombre IS NOT NULL AND contacto_email IS NOT NULL AND contacto_telefono IS NOT NULL)),
    CONSTRAINT chk_res_monto_total  CHECK (monto_total >= 0),
    CONSTRAINT chk_res_monto_pagado CHECK (monto_pagado >= 0 AND monto_pagado <= monto_total),
    CONSTRAINT chk_res_estado       CHECK (estado_reserva IN ('PENDIENTE', 'CONFIRMADA', 'ANULADA', 'COMPLETADA')),
    CONSTRAINT chk_res_estado_pago  CHECK (estado_pago IN ('PENDIENTE', 'PARCIAL', 'PAGADO', 'REEMBOLSADO')),
    CONSTRAINT chk_res_anulacion    CHECK (
        estado_reserva = 'ANULADA' OR (usuario_anula_id IS NULL AND forma_reembolso IS NULL)),
    CONSTRAINT fk_reserva_cliente FOREIGN KEY (cliente_id)       REFERENCES CLIENTES(cliente_id),
    CONSTRAINT fk_reserva_usuario FOREIGN KEY (usuario_anula_id) REFERENCES USUARIOS_SISTEMA(usuario_id)
)
STORAGE (INITIAL 1M NEXT 1M MINEXTENTS 3);

CREATE TABLE DETALLE_RESERVA (
    detalle_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id      NUMBER NOT NULL,
    salida_id       NUMBER NOT NULL,
    cantidad        NUMBER(2) NOT NULL,
    precio_unitario NUMBER(10,2) NOT NULL,       -- si va NULL, el trigger copia PAQUETES_TOUR.precio_base
    descuento       NUMBER(10,2) DEFAULT 0 NOT NULL,
    subtotal        NUMBER(10,2) GENERATED ALWAYS AS (cantidad * precio_unitario - descuento) VIRTUAL,
    CONSTRAINT chk_det_cantidad  CHECK (cantidad > 0),
    CONSTRAINT chk_det_precio    CHECK (precio_unitario >= 0),
    CONSTRAINT chk_det_descuento CHECK (descuento >= 0 AND descuento <= cantidad * precio_unitario),
    CONSTRAINT uq_det_reserva_salida UNIQUE (reserva_id, salida_id),
    CONSTRAINT fk_detalle_reserva FOREIGN KEY (reserva_id) REFERENCES RESERVAS(reserva_id),
    CONSTRAINT fk_detalle_salida  FOREIGN KEY (salida_id)  REFERENCES SALIDAS_PROGRAMADAS(salida_id)
)
STORAGE (INITIAL 640K NEXT 640K MINEXTENTS 3);

CREATE TABLE PASAJEROS_RESERVA (
    pasajero_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    detalle_id       NUMBER NOT NULL,
    nombre_completo  VARCHAR2(150) NOT NULL,
    tipo_documento   VARCHAR2(20)  NOT NULL,
    numero_documento VARCHAR2(20)  NOT NULL,
    nacionalidad     VARCHAR2(50),
    fecha_nacimiento DATE,
    CONSTRAINT chk_pas_tipo_doc   CHECK (tipo_documento IN ('DNI', 'CE', 'PASAPORTE')),
    CONSTRAINT uq_pas_detalle_doc UNIQUE (detalle_id, tipo_documento, numero_documento),
    CONSTRAINT fk_pasajero_detalle FOREIGN KEY (detalle_id) REFERENCES DETALLE_RESERVA(detalle_id)
)
STORAGE (INITIAL 640K NEXT 640K MINEXTENTS 3);

CREATE TABLE PAGOS (
    pago_id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id         NUMBER NOT NULL,
    monto              NUMBER(10,2) NOT NULL,
    moneda             VARCHAR2(10) DEFAULT 'PEN',
    tipo_cambio        NUMBER(8,4)  DEFAULT 1 NOT NULL,
    monto_pen          NUMBER(10,2) GENERATED ALWAYS AS (ROUND(monto * tipo_cambio, 2)) VIRTUAL,
    metodo_pago        VARCHAR2(50),
    codigo_transaccion VARCHAR2(100),
    fecha_pago         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    estado_transaccion VARCHAR2(20),
    CONSTRAINT chk_pago_monto  CHECK (monto > 0),
    CONSTRAINT chk_pago_moneda CHECK (moneda IN ('PEN', 'USD', 'EUR')),
    CONSTRAINT chk_pago_tc     CHECK (tipo_cambio > 0 AND (moneda <> 'PEN' OR tipo_cambio = 1)),
    CONSTRAINT chk_pago_estado CHECK (estado_transaccion IN ('PENDIENTE', 'APROBADO', 'RECHAZADO', 'REEMBOLSADO')),
    CONSTRAINT fk_pago_reserva FOREIGN KEY (reserva_id) REFERENCES RESERVAS(reserva_id)
)
STORAGE (INITIAL 640K NEXT 640K MINEXTENTS 3);

-- =====================================================================
-- 5. TRÁFICO DE TRANSPORTES (Punto 3)
-- =====================================================================
CREATE SEQUENCE SEQ_CODIGO_OPERACION START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE OPERACION_TRANSPORTE (
    operacion_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_operacion       VARCHAR2(15) NOT NULL,          -- KMP-001 (lo genera el trigger)
    salida_id              NUMBER,                         -- opcional: a qué salida/tour atiende
    origen_id              NUMBER NOT NULL,
    destino_id             NUMBER NOT NULL,
    empresa_id             NUMBER,
    vehiculo_id            NUMBER,
    conductor_id           NUMBER,
    pax_programados        NUMBER(3) NOT NULL,
    hora_programada_salida DATE NOT NULL,
    hora_estimada_llegada  DATE NOT NULL,                  -- si va NULL, se calcula con la ruta
    estado_actual          VARCHAR2(20) DEFAULT 'PROGRAMADO' NOT NULL,
    observaciones          VARCHAR2(200),
    CONSTRAINT uq_op_codigo    UNIQUE (codigo_operacion),
    CONSTRAINT chk_op_codigo   CHECK (REGEXP_LIKE(codigo_operacion, '^KMP-[0-9]{3,}$')),
    CONSTRAINT chk_op_od       CHECK (origen_id <> destino_id),
    CONSTRAINT chk_op_pax      CHECK (pax_programados > 0),
    CONSTRAINT chk_op_horas    CHECK (hora_estimada_llegada > hora_programada_salida),
    -- Con columnas NULL una FK compuesta no se valida: por eso se exige empresa
