-- 1. MAESTRAS COMERCIALES
-- =====================================================================
CREATE TABLE USUARIOS_SISTEMA (
    usuario_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR2(50)  NOT NULL UNIQUE,
    password_hash VARCHAR2(255) NOT NULL,
    rol           VARCHAR2(50)  NOT NULL,
    estado        VARCHAR2(20)  DEFAULT 'ACTIVO',
    CONSTRAINT chk_usu_rol    CHECK (rol IN ('ADMIN', 'VENDEDOR', 'OPERADOR')),  -- ajusta a tus roles
    CONSTRAINT chk_usu_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE CLIENTES (
    cliente_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo  VARCHAR2(150) NOT NULL,
    tipo_documento   VARCHAR2(20)  NOT NULL,
    numero_documento VARCHAR2(20)  NOT NULL,
    email            VARCHAR2(100) NOT NULL,
    telefono         VARCHAR2(20)  NOT NULL,  -- con código de país: '+51 987654321'
    CONSTRAINT chk_cli_tipo_doc CHECK (tipo_documento IN ('DNI', 'CE', 'PASAPORTE', 'RUC')),
    CONSTRAINT uq_cli_tipo_doc  UNIQUE (tipo_documento, numero_documento)
);

CREATE TABLE GUIAS (
    guia_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo VARCHAR2(150) NOT NULL,
    especialidad    VARCHAR2(100),
    telefono        VARCHAR2(20)
);

CREATE TABLE PAQUETES_TOUR (
    paquete_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR2(100) NOT NULL,
    descripcion VARCHAR2(1000),
    precio_base NUMBER(10,2) NOT NULL,
    dias        NUMBER(2) NOT NULL,
    noches      NUMBER(2) NOT NULL,
    imagen      VARCHAR2(500),
    estado      VARCHAR2(20) DEFAULT 'ACTIVO',
    CONSTRAINT chk_paq_precio CHECK (precio_base > 0),
    CONSTRAINT chk_paq_dias   CHECK (dias > 0 AND noches >= 0 AND noches <= dias),
    CONSTRAINT chk_paq_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
)
STORAGE (INITIAL 640K NEXT 640K MINEXTENTS 3);

-- =====================================================================
-- 2. EMPRESAS PROVEEDORAS DE TRANSPORTE (Punto 2)
-- =====================================================================
-- capacidad_total_transporte NO se guarda: se calcula en VW_EMPRESA_CAPACIDAD
-- (si se guardara, quedaría desactualizada al agregar/retirar vehículos).
CREATE TABLE EMPRESA_TRANSPORTE (
    empresa_id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_comercial         VARCHAR2(150) NOT NULL,
    ruc                      CHAR(11)      NOT NULL,
    contacto_nombre          VARCHAR2(150),
    contacto_telefono        VARCHAR2(20)  NOT NULL,
    contacto_email           VARCHAR2(100),
    direccion                VARCHAR2(250),
    estado_afiliacion        VARCHAR2(20)  DEFAULT 'PENDIENTE'  NOT NULL,
    disponibilidad_operativa VARCHAR2(20)  DEFAULT 'DISPONIBLE' NOT NULL,
    fecha_afiliacion         DATE          DEFAULT SYSDATE,
    CONSTRAINT uq_emp_ruc        UNIQUE (ruc),
    CONSTRAINT chk_emp_ruc       CHECK (REGEXP_LIKE(ruc, '^(10|15|17|20)[0-9]{9}$')),
    CONSTRAINT chk_emp_afiliacion CHECK (estado_afiliacion IN ('PENDIENTE', 'ACTIVA', 'SUSPENDIDA', 'RETIRADA')),
    CONSTRAINT chk_emp_disponib  CHECK (disponibilidad_operativa IN ('DISPONIBLE', 'LIMITADA', 'NO_DISPONIBLE'))
);

-- Orígenes y destinos (aeropuerto, hoteles, atractivos...)
CREATE TABLE LUGARES (
    lugar_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR2(150) NOT NULL,
    tipo_lugar VARCHAR2(20)  NOT NULL,
    ciudad     VARCHAR2(100) NOT NULL,
    CONSTRAINT chk_lug_tipo  CHECK (tipo_lugar IN ('AEROPUERTO', 'TERMINAL', 'HOTEL', 'ATRACTIVO', 'CIUDAD', 'OTRO')),
    CONSTRAINT uq_lug_nombre UNIQUE (nombre, ciudad)
);

-- Rutas/servicios que opera cada empresa
CREATE TABLE RUTAS_PROVEEDOR (
    ruta_id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id            NUMBER NOT NULL,
    origen_id             NUMBER NOT NULL,
    destino_id            NUMBER NOT NULL,
    tipo_servicio         VARCHAR2(20) DEFAULT 'TRASLADO' NOT NULL,
    duracion_estimada_min NUMBER(4) NOT NULL,
    tarifa_referencial    NUMBER(10,2),
    estado                VARCHAR2(20) DEFAULT 'ACTIVA' NOT NULL,
    CONSTRAINT chk_ruta_od        CHECK (origen_id <> destino_id),
    CONSTRAINT chk_ruta_duracion  CHECK (duracion_estimada_min > 0),
    CONSTRAINT chk_ruta_tarifa    CHECK (tarifa_referencial IS NULL OR tarifa_referencial >= 0),
    CONSTRAINT chk_ruta_servicio  CHECK (tipo_servicio IN ('TRASLADO', 'TOUR', 'INTERPROVINCIAL')),
    CONSTRAINT chk_ruta_estado    CHECK (estado IN ('ACTIVA', 'INACTIVA')),
    CONSTRAINT uq_ruta_emp_od     UNIQUE (empresa_id, origen_id, destino_id),
    CONSTRAINT fk_ruta_empresa    FOREIGN KEY (empresa_id) REFERENCES EMPRESA_TRANSPORTE(empresa_id),
    CONSTRAINT fk_ruta_origen     FOREIGN KEY (origen_id)  REFERENCES LUGARES(lugar_id),
    CONSTRAINT fk_ruta_destino    FOREIGN KEY (destino_id) REFERENCES LUGARES(lugar_id)
);

CREATE TABLE VEHICULO (
    vehiculo_id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id               NUMBER NOT NULL,
    placa                    VARCHAR2(10) NOT NULL,
    tipo_vehiculo            VARCHAR2(20) NOT NULL,
    marca_modelo             VARCHAR2(100),
    capacidad_pax            NUMBER(3) NOT NULL,
    fecha_prox_mantenimiento DATE NOT NULL,
    estado_operativo         VARCHAR2(20) DEFAULT 'OPERATIVO' NOT NULL,
    CONSTRAINT uq_veh_placa      UNIQUE (placa),
    CONSTRAINT uq_veh_empresa    UNIQUE (vehiculo_id, empresa_id),   -- para la FK compuesta
    CONSTRAINT chk_veh_tipo      CHECK (tipo_vehiculo IN ('AUTO', 'CAMIONETA_4X4', 'VAN', 'MINIBUS', 'BUS')),
    CONSTRAINT chk_veh_capacidad CHECK (capacidad_pax > 0),
    CONSTRAINT chk_veh_estado    CHECK (estado_operativo IN ('OPERATIVO', 'EN_MANTENIMIENTO', 'FUERA_DE_SERVICIO')),
    CONSTRAINT fk_veh_empresa    FOREIGN KEY (empresa_id) REFERENCES EMPRESA_TRANSPORTE(empresa_id)
);

-- horas_trabajadas_acumuladas NO se guarda: PKG_ASIGNACION.horas_conductor_dia
-- la calcula desde OPERACION_TRANSPORTE (un acumulado guardado se desfasa
-- cuando una operación se reprograma o se cancela).
CREATE TABLE CONDUCTOR (
    conductor_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id            NUMBER NOT NULL,
    nombres               VARCHAR2(150) NOT NULL,
    numero_licencia       VARCHAR2(20)  NOT NULL,
    categoria_licencia    VARCHAR2(10)  NOT NULL,
    fecha_venc_licencia   DATE          NOT NULL,
    telefono              VARCHAR2(20),
    estado_disponibilidad VARCHAR2(20)  DEFAULT 'DISPONIBLE' NOT NULL,
    CONSTRAINT uq_cond_licencia  UNIQUE (numero_licencia),
    CONSTRAINT uq_cond_empresa   UNIQUE (conductor_id, empresa_id),  -- para la FK compuesta
    CONSTRAINT chk_cond_categoria CHECK (categoria_licencia IN ('A-IIa', 'A-IIb', 'A-IIIa', 'A-IIIb', 'A-IIIc')),
    CONSTRAINT chk_cond_estado   CHECK (estado_disponibilidad IN ('DISPONIBLE', 'DESCANSO', 'VACACIONES', 'INACTIVO')),
    CONSTRAINT fk_cond_empresa   FOREIGN KEY (empresa_id) REFERENCES EMPRESA_TRANSPORTE(empresa_id)
);

