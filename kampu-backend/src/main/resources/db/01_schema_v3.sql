-- 10.1 Salida: fecha_fin según días del paquete y cupos_disponibles automáticos
CREATE OR REPLACE TRIGGER trg_salida_biu
BEFORE INSERT OR UPDATE OF paquete_id, fecha_inicio, fecha_fin, cupos_maximos
ON SALIDAS_PROGRAMADAS
FOR EACH ROW
DECLARE
    v_dias PAQUETES_TOUR.dias%TYPE;
BEGIN
    SELECT dias INTO v_dias FROM PAQUETES_TOUR WHERE paquete_id = :NEW.paquete_id;

    IF :NEW.fecha_fin IS NULL THEN
        :NEW.fecha_fin := TRUNC(:NEW.fecha_inicio) + v_dias - 1;
    ELSIF TRUNC(:NEW.fecha_fin) <> TRUNC(:NEW.fecha_inicio) + v_dias - 1 THEN
        RAISE_APPLICATION_ERROR(-20010,
            'fecha_fin no coincide con los ' || v_dias || ' día(s) del paquete');
    END IF;

    IF INSERTING THEN
        :NEW.cupos_disponibles := :NEW.cupos_maximos;      -- salida nueva = sin reservas
    ELSIF UPDATING('cupos_maximos') THEN
        :NEW.cupos_disponibles := :OLD.cupos_disponibles + (:NEW.cupos_maximos - :OLD.cupos_maximos);
        IF :NEW.cupos_disponibles < 0 THEN
            RAISE_APPLICATION_ERROR(-20013,
                'No puedes bajar cupos_maximos por debajo de los cupos ya vendidos');
        END IF;
    END IF;
END;
/

-- 10.1b Confirmar una salida exige transporte suficiente en todos sus tramos
CREATE OR REPLACE TRIGGER trg_salida_confirmar
BEFORE UPDATE OF estado ON SALIDAS_PROGRAMADAS
FOR EACH ROW
WHEN (NEW.estado = 'CONFIRMADA' AND OLD.estado <> 'CONFIRMADA')
DECLARE
    v_faltante VARCHAR2(400);
BEGIN
    v_faltante := PKG_ASIGNACION.faltante_transporte(
                      :NEW.salida_id, :NEW.cupos_maximos - :NEW.cupos_disponibles);
    IF v_faltante IS NOT NULL THEN
        RAISE_APPLICATION_ERROR(-20014,
            'No se puede confirmar la salida ' || :NEW.salida_id || ': ' || v_faltante);
    END IF;
END;
/

-- 10.2 Detalle: valida la salida, descuenta/devuelve cupos, congela precio
--      y actualiza RESERVAS.monto_total
CREATE OR REPLACE TRIGGER trg_detalle_reserva_biud
BEFORE INSERT OR UPDATE OR DELETE ON DETALLE_RESERVA
FOR EACH ROW
DECLARE
    v_reserva_id NUMBER := COALESCE(:NEW.reserva_id, :OLD.reserva_id);
    v_est_res    RESERVAS.estado_reserva%TYPE;
    v_est_sal    SALIDAS_PROGRAMADAS.estado%TYPE;
    v_cupos      SALIDAS_PROGRAMADAS.cupos_disponibles%TYPE;
    v_cupos_max  SALIDAS_PROGRAMADAS.cupos_maximos%TYPE;
    v_faltante   VARCHAR2(400);
    v_precio     PAQUETES_TOUR.precio_base%TYPE;
    v_pasajeros  NUMBER;
    v_sub_old    NUMBER := 0;
    v_sub_new    NUMBER := 0;
BEGIN
    IF UPDATING('reserva_id') AND :NEW.reserva_id <> :OLD.reserva_id THEN
        RAISE_APPLICATION_ERROR(-20020, 'Un detalle no puede cambiarse de reserva');
    END IF;

    SELECT estado_reserva INTO v_est_res
      FROM RESERVAS WHERE reserva_id = v_reserva_id FOR UPDATE;
    IF v_est_res IN ('ANULADA', 'COMPLETADA') THEN
        RAISE_APPLICATION_ERROR(-20021,
            'La reserva ' || v_reserva_id || ' está ' || v_est_res || ' y no se puede modificar');
    END IF;

    IF UPDATING OR DELETING THEN
        UPDATE SALIDAS_PROGRAMADAS
           SET cupos_disponibles = cupos_disponibles + :OLD.cantidad
         WHERE salida_id = :OLD.salida_id;
        v_sub_old := :OLD.cantidad * :OLD.precio_unitario - :OLD.descuento;
    END IF;

    IF INSERTING OR UPDATING THEN
        SELECT s.estado, s.cupos_disponibles, s.cupos_maximos, p.precio_base
          INTO v_est_sal, v_cupos, v_cupos_max, v_precio
          FROM SALIDAS_PROGRAMADAS s
          JOIN PAQUETES_TOUR p ON p.paquete_id = s.paquete_id
         WHERE s.salida_id = :NEW.salida_id
           FOR UPDATE OF s.cupos_disponibles;

        IF v_est_sal NOT IN ('PROGRAMADA', 'CONFIRMADA') THEN
            RAISE_APPLICATION_ERROR(-20022,
                'La salida ' || :NEW.salida_id || ' está ' || v_est_sal || ' y no acepta reservas');
        END IF;

        IF v_cupos < :NEW.cantidad THEN
            RAISE_APPLICATION_ERROR(-20023,
                'Solo quedan ' || v_cupos || ' cupo(s) en la salida ' || :NEW.salida_id);
        END IF;

        IF UPDATING THEN
            SELECT COUNT(*) INTO v_pasajeros
              FROM PASAJEROS_RESERVA WHERE detalle_id = :NEW.detalle_id;
            IF v_pasajeros > :NEW.cantidad THEN
                RAISE_APPLICATION_ERROR(-20024,
                    'Hay ' || v_pasajeros || ' pasajeros registrados; la cantidad no puede ser menor');
            END IF;
        END IF;

        IF :NEW.precio_unitario IS NULL THEN
            :NEW.precio_unitario := v_precio;
        END IF;

        -- Salida ya CONFIRMADA: solo se vende lo que el transporte asignado puede llevar
        IF v_est_sal = 'CONFIRMADA' THEN
            v_faltante := PKG_ASIGNACION.faltante_transporte(
                              :NEW.salida_id, v_cupos_max - (v_cupos - :NEW.cantidad));
            IF v_faltante IS NOT NULL THEN
                RAISE_APPLICATION_ERROR(-20025,
                    'Sin transporte suficiente para vender ' || :NEW.cantidad
                    || ' cupo(s) más en la salida ' || :NEW.salida_id || ': ' || v_faltante);
            END IF;
        END IF;

        UPDATE SALIDAS_PROGRAMADAS
           SET cupos_disponibles = cupos_disponibles - :NEW.cantidad
         WHERE salida_id = :NEW.salida_id;

        v_sub_new := :NEW.cantidad * :NEW.precio_unitario - NVL(:NEW.descuento, 0);
    END IF;

    UPDATE RESERVAS
       SET monto_total = monto_total - v_sub_old + v_sub_new
     WHERE reserva_id = v_reserva_id;
END;
/

-- 10.3 Reserva: al ANULAR se devuelven los cupos; una anulada no se reactiva
CREATE OR REPLACE TRIGGER trg_reserva_estado_bu
BEFORE UPDATE OF estado_reserva ON RESERVAS
FOR EACH ROW
BEGIN
    IF :OLD.estado_reserva = 'ANULADA' AND :NEW.estado_reserva <> 'ANULADA' THEN
        RAISE_APPLICATION_ERROR(-20030, 'Una reserva ANULADA no puede reactivarse');
    END IF;

    IF :NEW.estado_reserva = 'ANULADA' AND :OLD.estado_reserva <> 'ANULADA' THEN
        IF :NEW.usuario_anula_id IS NULL THEN
            RAISE_APPLICATION_ERROR(-20031, 'Indica usuario_anula_id para anular la reserva');
        END IF;

        FOR d IN (SELECT salida_id, cantidad
                    FROM DETALLE_RESERVA
                   WHERE reserva_id = :NEW.reserva_id) LOOP
            UPDATE SALIDAS_PROGRAMADAS
               SET cupos_disponibles = cupos_disponibles + d.cantidad
             WHERE salida_id = d.salida_id;
        END LOOP;
    END IF;
END;
/

-- 10.4 Pasajeros: no más pasajeros que la cantidad del detalle
CREATE OR REPLACE TRIGGER trg_pasajeros_cupo
FOR INSERT OR UPDATE OF detalle_id ON PASAJEROS_RESERVA
COMPOUND TRIGGER
    TYPE t_ids IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
    g_ids t_ids;

    AFTER EACH ROW IS
    BEGIN
        g_ids(g_ids.COUNT + 1) := :NEW.detalle_id;
    END AFTER EACH ROW;

    AFTER STATEMENT IS
        v_cantidad    NUMBER;
        v_registrados NUMBER;
    BEGIN
        FOR i IN 1 .. g_ids.COUNT LOOP
            SELECT cantidad INTO v_cantidad
              FROM DETALLE_RESERVA WHERE detalle_id = g_ids(i);
            SELECT COUNT(*) INTO v_registrados
              FROM PASAJEROS_RESERVA WHERE detalle_id = g_ids(i);
            IF v_registrados > v_cantidad THEN
                RAISE_APPLICATION_ERROR(-20040,
                    'El detalle ' || g_ids(i) || ' admite ' || v_cantidad || ' pasajero(s)');
            END IF;
        END LOOP;
    END AFTER STATEMENT;
END trg_pasajeros_cupo;
/

-- 10.5 Operaciones de transporte (Puntos 1 y 3)
--   BEFORE EACH ROW : código KMP-###, llegada estimada, transiciones válidas,
--                     recursos obligatorios, ruta activa y bloqueo del recurso
--   AFTER EACH ROW  : registra el historial de estados
--   AFTER STATEMENT : valida cruces, descanso y mantenimiento (aquí ya se puede
--                     consultar OPERACION_TRANSPORTE sin error de tabla mutante)
--                     y que el transporte de la salida siga alcanzando
CREATE OR REPLACE TRIGGER trg_operacion_transporte
FOR INSERT OR UPDATE ON OPERACION_TRANSPORTE
COMPOUND TRIGGER
    TYPE t_ids IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
    g_validar  t_ids;   -- operaciones a validar (cruces, descanso, mantenimiento)
    g_salidas  t_ids;   -- salidas cuyo transporte pudo reducirse
    g_embarque t_ids;   -- operaciones que pasan a EMBARQUE

    BEFORE EACH ROW IS
        v_requiere DOMINIO_ESTADOS.requiere_recursos%TYPE;
        v_final    DOMINIO_ESTADOS.es_final%TYPE;
        v_existe   NUMBER;
        v_duracion NUMBER;
        v_ruta_est RUTAS_PROVEEDOR.estado%TYPE;
    BEGIN
        -- Operación cerrada: no se modifica
        IF UPDATING THEN
            SELECT es_final INTO v_final
              FROM DOMINIO_ESTADOS WHERE codigo_estado = :OLD.estado_actual;
            IF v_final = 'S' THEN
                RAISE_APPLICATION_ERROR(-20050,
                    :OLD.codigo_operacion || ' está ' || :OLD.estado_actual || ' y no se puede modificar');
            END IF;
        END IF;

        IF INSERTING AND :NEW.codigo_operacion IS NULL THEN
            :NEW.codigo_operacion := 'KMP-' || LPAD(SEQ_CODIGO_OPERACION.NEXTVAL, 3, '0');
        END IF;

        IF :NEW.hora_estimada_llegada IS NULL THEN
            SELECT MIN(duracion_estimada_min) INTO v_duracion
              FROM RUTAS_PROVEEDOR
             WHERE origen_id = :NEW.origen_id
               AND destino_id = :NEW.destino_id
               AND (:NEW.empresa_id IS NULL OR empresa_id = :NEW.empresa_id);
            IF v_duracion IS NULL THEN
                RAISE_APPLICATION_ERROR(-20051,
                    'Ninguna empresa opera esa ruta; indique hora_estimada_llegada');
            END IF;
            :NEW.hora_estimada_llegada := :NEW.hora_programada_salida + v_duracion / 1440;
        END IF;

        -- Transición permitida
        IF UPDATING AND :NEW.estado_actual <> :OLD.estado_actual THEN
            SELECT COUNT(*) INTO v_existe
              FROM DOMINIO_TRANSICIONES
             WHERE estado_origen = :OLD.estado_actual
               AND estado_destino = :NEW.estado_actual;
            IF v_existe = 0 THEN
                RAISE_APPLICATION_ERROR(-20052,
                    'Transición no permitida: ' || :OLD.estado_actual || ' -> ' || :NEW.estado_actual);
            END IF;

            -- Volver a PROGRAMADO libera el vehículo y el conductor
            IF :NEW.estado_actual = 'PROGRAMADO' THEN
                :NEW.vehiculo_id  := NULL;
                :NEW.conductor_id := NULL;
            END IF;
        END IF;

        -- Estados que exigen recursos asignados
        BEGIN
            SELECT requiere_recursos INTO v_requiere
              FROM DOMINIO_ESTADOS WHERE codigo_estado = :NEW.estado_actual;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20053, 'Estado inexistente: ' || :NEW.estado_actual);
        END;
        IF v_requiere = 'S' AND (:NEW.vehiculo_id IS NULL OR :NEW.conductor_id IS NULL) THEN
            RAISE_APPLICATION_ERROR(-20054,
                'El estado ' || :NEW.estado_actual || ' requiere vehículo y conductor asignados');
        END IF;

        -- La ruta de la empresa debe estar ACTIVA
        IF :NEW.empresa_id IS NOT NULL
           AND (INSERTING OR UPDATING('empresa_id') OR UPDATING('origen_id') OR UPDATING('destino_id')) THEN
            BEGIN
                SELECT estado INTO v_ruta_est
                  FROM RUTAS_PROVEEDOR
                 WHERE empresa_id = :NEW.empresa_id
                   AND origen_id  = :NEW.origen_id
                   AND destino_id = :NEW.destino_id;
                IF v_ruta_est <> 'ACTIVA' THEN
                    RAISE_APPLICATION_ERROR(-20055, 'La ruta de esa empresa está INACTIVA');
                END IF;
            EXCEPTION
                WHEN NO_DATA_FOUND THEN NULL;   -- lo reporta la FK fk_op_ruta
            END;
        END IF;

        -- Bloquea el vehículo/conductor para que dos sesiones no los asignen a la vez
        IF :NEW.vehiculo_id IS NOT NULL THEN
            BEGIN
                SELECT 1 INTO v_existe FROM VEHICULO
                 WHERE vehiculo_id = :NEW.vehiculo_id FOR UPDATE;
            EXCEPTION WHEN NO_DATA_FOUND THEN NULL;   -- lo reporta la FK
            END;
        END IF;
        IF :NEW.conductor_id IS NOT NULL THEN
            BEGIN
                SELECT 1 INTO v_existe FROM CONDUCTOR
                 WHERE conductor_id = :NEW.conductor_id FOR UPDATE;
            EXCEPTION WHEN NO_DATA_FOUND THEN NULL;
            END;
        END IF;
    END BEFORE EACH ROW;

    AFTER EACH ROW IS
    BEGIN
        IF INSERTING OR :NEW.estado_actual <> :OLD.estado_actual THEN
            INSERT INTO HISTORIAL_TRAFICO_OPERACION
                   (operacion_id, estado_anterior, estado_nuevo, usuario_registro)
            VALUES (:NEW.operacion_id, :OLD.estado_actual, :NEW.estado_actual,
                    NVL(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'), USER));
        END IF;

        IF (:NEW.vehiculo_id IS NOT NULL OR :NEW.conductor_id IS NOT NULL)
           AND (INSERTING
                OR UPDATING('vehiculo_id') OR UPDATING('conductor_id')
                OR UPDATING('hora_programada_salida') OR UPDATING('hora_estimada_llegada')
                OR UPDATING('pax_programados')) THEN
            g_validar(g_validar.COUNT + 1) := :NEW.operacion_id;
        END IF;

        -- Cambios que pueden dejar a la salida con menos capacidad
        IF UPDATING AND :OLD.salida_id IS NOT NULL
           AND (UPDATING('vehiculo_id') OR UPDATING('salida_id')
                OR UPDATING('origen_id') OR UPDATING('destino_id')
                OR UPDATING('hora_programada_salida')
                OR (:NEW.estado_actual <> :OLD.estado_actual
                    AND :NEW.estado_actual IN ('CANCELADO', 'PROGRAMADO'))) THEN
            g_salidas(g_salidas.COUNT + 1) := :OLD.salida_id;
        END IF;

        -- Para embarcar, el tramo debe llevar a todos los pasajeros de la salida
        IF :NEW.salida_id IS NOT NULL AND :NEW.estado_actual = 'EMBARQUE'
           AND (INSERTING OR :OLD.estado_actual <> 'EMBARQUE') THEN
            g_embarque(g_embarque.COUNT + 1) := :NEW.operacion_id;
        END IF;
    END AFTER EACH ROW;

    AFTER STATEMENT IS
        v_motivo VARCHAR2(400);
    BEGIN
        FOR i IN 1 .. g_validar.COUNT LOOP
            FOR o IN (SELECT operacion_id, codigo_operacion, vehiculo_id, conductor_id,
                             pax_programados, hora_programada_salida, hora_estimada_llegada
                        FROM OPERACION_TRANSPORTE
                       WHERE operacion_id = g_validar(i)) LOOP
                IF o.vehiculo_id IS NOT NULL THEN
                    v_motivo := PKG_ASIGNACION.motivo_vehiculo(o.vehiculo_id,
                                    o.hora_programada_salida, o.hora_estimada_llegada,
                                    o.pax_programados, o.operacion_id);
                    IF v_motivo IS NOT NULL THEN
                        RAISE_APPLICATION_ERROR(-20060, o.codigo_operacion || ' - vehículo: ' || v_motivo);
                    END IF;
                END IF;
                IF o.conductor_id IS NOT NULL THEN
                    v_motivo := PKG_ASIGNACION.motivo_conductor(o.conductor_id,
                                    o.hora_programada_salida, o.hora_estimada_llegada,
                                    o.operacion_id);
                    IF v_motivo IS NOT NULL THEN
                        RAISE_APPLICATION_ERROR(-20061, o.codigo_operacion || ' - conductor: ' || v_motivo);
                    END IF;
                END IF;
            END LOOP;
        END LOOP;

        -- Salidas CONFIRMADAS: no se puede quitar capacidad que hace falta
        -- (para reemplazar un vehículo: crea/asigna el nuevo primero y luego cancela el otro)
        FOR i IN 1 .. g_salidas.COUNT LOOP
            FOR s IN (SELECT salida_id, cupos_maximos - cupos_disponibles AS pasajeros
                        FROM SALIDAS_PROGRAMADAS
                       WHERE salida_id = g_salidas(i)
                         AND estado = 'CONFIRMADA') LOOP
                v_motivo := PKG_ASIGNACION.faltante_transporte(s.salida_id, s.pasajeros);
                IF v_motivo IS NOT NULL THEN
                    RAISE_APPLICATION_ERROR(-20062,
                        'La salida confirmada ' || s.salida_id || ' quedaría sin transporte suficiente: ' || v_motivo);
                END IF;
            END LOOP;
        END LOOP;

        -- Embarque: el tramo debe tener capacidad para todos los pasajeros vendidos
        FOR i IN 1 .. g_embarque.COUNT LOOP
            FOR o IN (SELECT op.codigo_operacion, op.salida_id,
                             s.cupos_maximos - s.cupos_disponibles AS pasajeros
                        FROM OPERACION_TRANSPORTE op
                        JOIN SALIDAS_PROGRAMADAS s ON s.salida_id = op.salida_id
                       WHERE op.operacion_id = g_embarque(i)) LOOP
                v_motivo := PKG_ASIGNACION.faltante_transporte(o.salida_id, o.pasajeros, g_embarque(i));
                IF v_motivo IS NOT NULL THEN
                    RAISE_APPLICATION_ERROR(-20063,
                        o.codigo_operacion || ' no puede embarcar: ' || v_motivo);
                END IF;
            END LOOP;
        END LOOP;
    END AFTER STATEMENT;
END trg_operacion_transporte;
/

