-- 8.1 Recursos elegibles para cada operación pendiente (PROGRAMADO).
--     Cruza: empresa afiliada y disponible, ruta activa, estado operativo,
--     capacidad, mantenimiento, licencia, horas del día y horarios ocupados.
CREATE OR REPLACE VIEW VW_RECURSOS_DISPONIBLES AS
SELECT o.operacion_id,
       o.codigo_operacion,
       'VEHICULO'                                AS tipo_recurso,
       v.vehiculo_id                             AS recurso_id,
       e.empresa_id,
       e.nombre_comercial                        AS empresa,
       v.placa || ' - ' || v.tipo_vehiculo       AS descripcion,
       v.capacidad_pax,
       v.capacidad_pax - o.pax_programados       AS holgura_pax,
       CAST(NULL AS NUMBER)                      AS horas_dia
  FROM OPERACION_TRANSPORTE o
  JOIN RUTAS_PROVEEDOR    r ON r.origen_id = o.origen_id AND r.destino_id = o.destino_id
                           AND r.estado = 'ACTIVA'
  JOIN EMPRESA_TRANSPORTE e ON e.empresa_id = r.empresa_id
  JOIN VEHICULO           v ON v.empresa_id = r.empresa_id
 WHERE o.estado_actual = 'PROGRAMADO'
   AND (o.empresa_id IS NULL OR o.empresa_id = r.empresa_id)
   AND e.estado_afiliacion = 'ACTIVA'
   AND e.disponibilidad_operativa <> 'NO_DISPONIBLE'
   AND v.estado_operativo = 'OPERATIVO'
   AND v.capacidad_pax >= o.pax_programados
   AND PKG_ASIGNACION.motivo_vehiculo(v.vehiculo_id, o.hora_programada_salida,
           o.hora_estimada_llegada, o.pax_programados, o.operacion_id) IS NULL
UNION ALL
SELECT o.operacion_id,
       o.codigo_operacion,
       'CONDUCTOR',
       c.conductor_id,
       e.empresa_id,
       e.nombre_comercial,
       c.nombres || ' (' || c.categoria_licencia || ')',
       CAST(NULL AS NUMBER),
       CAST(NULL AS NUMBER),
       PKG_ASIGNACION.horas_conductor_dia(c.conductor_id, o.hora_programada_salida, o.operacion_id)
  FROM OPERACION_TRANSPORTE o
  JOIN RUTAS_PROVEEDOR    r ON r.origen_id = o.origen_id AND r.destino_id = o.destino_id
                           AND r.estado = 'ACTIVA'
  JOIN EMPRESA_TRANSPORTE e ON e.empresa_id = r.empresa_id
  JOIN CONDUCTOR          c ON c.empresa_id = r.empresa_id
 WHERE o.estado_actual = 'PROGRAMADO'
   AND (o.empresa_id IS NULL OR o.empresa_id = r.empresa_id)
   AND e.estado_afiliacion = 'ACTIVA'
   AND e.disponibilidad_operativa <> 'NO_DISPONIBLE'
   AND c.estado_disponibilidad = 'DISPONIBLE'
   AND PKG_ASIGNACION.motivo_conductor(c.conductor_id, o.hora_programada_salida,
           o.hora_estimada_llegada, o.operacion_id) IS NULL;

-- 8.2 Tablero tipo FIDS con horas reales y retrasos (desde el historial)
CREATE OR REPLACE VIEW VW_TABLERO_OPERACIONES AS
SELECT o.operacion_id,
       o.codigo_operacion,
       lo.nombre                  AS origen,
       ld.nombre                  AS destino,
       e.nombre_comercial         AS empresa,
       v.placa,
       c.nombres                  AS conductor,
       o.pax_programados,
       o.hora_programada_salida,
       o.hora_estimada_llegada,
       es.nombre_mostrar          AS estado,
       es.orden                   AS orden_estado,
       hs.hora_real_salida,
       hl.hora_real_llegada,
       ROUND((CAST(hs.hora_real_salida  AS DATE) - o.hora_programada_salida) * 1440) AS min_retraso_salida,
       ROUND((CAST(hl.hora_real_llegada AS DATE) - o.hora_estimada_llegada)  * 1440) AS min_retraso_llegada
  FROM OPERACION_TRANSPORTE o
  JOIN LUGARES         lo ON lo.lugar_id = o.origen_id
  JOIN LUGARES         ld ON ld.lugar_id = o.destino_id
  JOIN DOMINIO_ESTADOS es ON es.codigo_estado = o.estado_actual
  LEFT JOIN EMPRESA_TRANSPORTE e ON e.empresa_id   = o.empresa_id
  LEFT JOIN VEHICULO           v ON v.vehiculo_id  = o.vehiculo_id
  LEFT JOIN CONDUCTOR          c ON c.conductor_id = o.conductor_id
  LEFT JOIN (SELECT operacion_id, MIN(fecha_cambio) AS hora_real_salida
               FROM HISTORIAL_TRAFICO_OPERACION
              WHERE estado_nuevo = 'EN_RUTA'
              GROUP BY operacion_id) hs ON hs.operacion_id = o.operacion_id
  LEFT JOIN (SELECT operacion_id, MAX(fecha_cambio) AS hora_real_llegada
               FROM HISTORIAL_TRAFICO_OPERACION
              WHERE estado_nuevo = 'FINALIZADO'
              GROUP BY operacion_id) hl ON hl.operacion_id = o.operacion_id;

