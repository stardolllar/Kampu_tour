-- 9. PKG_ASIGNACION - cuerpo
-- =====================================================================
CREATE OR REPLACE PACKAGE BODY PKG_ASIGNACION AS

    FUNCTION horas_conductor_dia (p_conductor_id NUMBER, p_fecha DATE,
                                  p_excluir_op NUMBER DEFAULT NULL) RETURN NUMBER IS
        v_horas NUMBER;
    BEGIN
        SELECT NVL(SUM((o.hora_estimada_llegada - o.hora_programada_salida) * 24), 0)
          INTO v_horas
          FROM OPERACION_TRANSPORTE o
          JOIN DOMINIO_ESTADOS e ON e.codigo_estado = o.estado_actual
         WHERE o.conductor_id = p_conductor_id
           AND e.ocupa_recursos = 'S'
           AND o.hora_programada_salida >= TRUNC(p_fecha)
           AND o.hora_programada_salida <  TRUNC(p_fecha) + 1
           AND (p_excluir_op IS NULL OR o.operacion_id <> p_excluir_op);
        RETURN ROUND(v_horas, 2);
    END horas_conductor_dia;

    FUNCTION operacion_en_cruce (p_tipo VARCHAR2, p_recurso_id NUMBER,
                                 p_salida DATE, p_llegada DATE,
                                 p_excluir_op NUMBER DEFAULT NULL) RETURN VARCHAR2 IS
        v_codigo OPERACION_TRANSPORTE.codigo_operacion%TYPE;
        v_margen NUMBER := c_margen_min / 1440;
    BEGIN
        -- Dos rangos [s1,l1] y [s2,l2] se cruzan si s1 < l2 y s2 < l1 (con margen)
        IF p_tipo = 'VEHICULO' THEN
            SELECT MIN(o.codigo_operacion) INTO v_codigo
              FROM OPERACION_TRANSPORTE o
              JOIN DOMINIO_ESTADOS e ON e.codigo_estado = o.estado_actual
             WHERE o.vehiculo_id = p_recurso_id
               AND e.ocupa_recursos = 'S'
               AND (p_excluir_op IS NULL OR o.operacion_id <> p_excluir_op)
               AND o.hora_programada_salida < p_llegada + v_margen
               AND p_salida < o.hora_estimada_llegada + v_margen;
        ELSE
            SELECT MIN(o.codigo_operacion) INTO v_codigo
              FROM OPERACION_TRANSPORTE o
              JOIN DOMINIO_ESTADOS e ON e.codigo_estado = o.estado_actual
             WHERE o.conductor_id = p_recurso_id
               AND e.ocupa_recursos = 'S'
               AND (p_excluir_op IS NULL OR o.operacion_id <> p_excluir_op)
               AND o.hora_programada_salida < p_llegada + v_margen
               AND p_salida < o.hora_estimada_llegada + v_margen;
        END IF;
        RETURN v_codigo;
    END operacion_en_cruce;

    FUNCTION motivo_vehiculo (p_vehiculo_id NUMBER, p_salida DATE, p_llegada DATE,
                              p_pax NUMBER, p_excluir_op NUMBER DEFAULT NULL) RETURN VARCHAR2 IS
        v_cap    VEHICULO.capacidad_pax%TYPE;
        v_estado VEHICULO.estado_operativo%TYPE;
        v_mant   VEHICULO.fecha_prox_mantenimiento%TYPE;
        v_afil   EMPRESA_TRANSPORTE.estado_afiliacion%TYPE;
        v_disp   EMPRESA_TRANSPORTE.disponibilidad_operativa%TYPE;
        v_cruce  VARCHAR2(15);
    BEGIN
        SELECT v.capacidad_pax, v.estado_operativo, v.fecha_prox_mantenimiento,
               e.estado_afiliacion, e.disponibilidad_operativa
          INTO v_cap, v_estado, v_mant, v_afil, v_disp
          FROM VEHICULO v
          JOIN EMPRESA_TRANSPORTE e ON e.empresa_id = v.empresa_id
         WHERE v.vehiculo_id = p_vehiculo_id;

        IF v_afil <> 'ACTIVA' THEN
            RETURN 'empresa con afiliación ' || v_afil;
        ELSIF v_disp = 'NO_DISPONIBLE' THEN
            RETURN 'empresa sin disponibilidad operativa';
        ELSIF v_estado <> 'OPERATIVO' THEN
            RETURN 'vehículo ' || v_estado;
        ELSIF p_pax > v_cap THEN
            RETURN 'capacidad insuficiente (' || v_cap || ' < ' || p_pax || ' pax)';
        ELSIF TRUNC(v_mant) <= TRUNC(p_llegada) THEN
            -- el viaje termina el día del mantenimiento o después (mantenimiento vencido)
            RETURN 'mantenimiento programado el ' || TO_CHAR(v_mant, 'DD/MM/YYYY');
        END IF;

        v_cruce := operacion_en_cruce('VEHICULO', p_vehiculo_id, p_salida, p_llegada, p_excluir_op);
        IF v_cruce IS NOT NULL THEN
            RETURN 'cruce de horario con ' || v_cruce;
        END IF;
        RETURN NULL;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RETURN 'vehículo inexistente';
    END motivo_vehiculo;

    FUNCTION motivo_conductor (p_conductor_id NUMBER, p_salida DATE, p_llegada DATE,
                               p_excluir_op NUMBER DEFAULT NULL) RETURN VARCHAR2 IS
        v_estado CONDUCTOR.estado_disponibilidad%TYPE;
        v_venc   CONDUCTOR.fecha_venc_licencia%TYPE;
        v_afil   EMPRESA_TRANSPORTE.estado_afiliacion%TYPE;
        v_disp   EMPRESA_TRANSPORTE.disponibilidad_operativa%TYPE;
        v_horas  NUMBER;
        v_cruce  VARCHAR2(15);
    BEGIN
        SELECT c.estado_disponibilidad, c.fecha_venc_licencia,
               e.estado_afiliacion, e.disponibilidad_operativa
          INTO v_estado, v_venc, v_afil, v_disp
          FROM CONDUCTOR c
          JOIN EMPRESA_TRANSPORTE e ON e.empresa_id = c.empresa_id
         WHERE c.conductor_id = p_conductor_id;

        IF v_afil <> 'ACTIVA' THEN
            RETURN 'empresa con afiliación ' || v_afil;
        ELSIF v_disp = 'NO_DISPONIBLE' THEN
            RETURN 'empresa sin disponibilidad operativa';
        ELSIF v_estado <> 'DISPONIBLE' THEN
            RETURN 'conductor en estado ' || v_estado;
        ELSIF TRUNC(v_venc) < TRUNC(p_llegada) THEN
            RETURN 'licencia vence el ' || TO_CHAR(v_venc, 'DD/MM/YYYY');
        END IF;

        v_horas := horas_conductor_dia(p_conductor_id, p_salida, p_excluir_op)
                 + (p_llegada - p_salida) * 24;
        IF v_horas > c_max_horas_dia THEN
            RETURN 'excede ' || c_max_horas_dia || ' h de conducción en el día ('
                   || TO_CHAR(v_horas, 'FM990.0') || ' h)';
        END IF;

        v_cruce := operacion_en_cruce('CONDUCTOR', p_conductor_id, p_salida, p_llegada, p_excluir_op);
        IF v_cruce IS NOT NULL THEN
            RETURN 'cruce de horario con ' || v_cruce;
        END IF;
        RETURN NULL;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RETURN 'conductor inexistente';
    END motivo_conductor;

    PROCEDURE asignar_automatico (p_operacion_id NUMBER) IS
        v_estado OPERACION_TRANSPORTE.estado_actual%TYPE;
        v_codigo OPERACION_TRANSPORTE.codigo_operacion%TYPE;
    BEGIN
        SELECT estado_actual, codigo_operacion INTO v_estado, v_codigo
          FROM OPERACION_TRANSPORTE
         WHERE operacion_id = p_operacion_id
           FOR UPDATE;

        IF v_estado <> 'PROGRAMADO' THEN
            RAISE_APPLICATION_ERROR(-20100,
                v_codigo || ' está en estado ' || v_estado || '; solo se asignan operaciones PROGRAMADO');
        END IF;

        -- Mejor par de la misma empresa: vehículo con menor asiento vacío,
        -- luego conductor con menos horas en el día
        FOR r IN (SELECT veh.empresa_id, veh.recurso_id AS vehiculo_id, con.recurso_id AS conductor_id
                    FROM VW_RECURSOS_DISPONIBLES veh
                    JOIN VW_RECURSOS_DISPONIBLES con
                      ON con.operacion_id = veh.operacion_id
                     AND con.empresa_id   = veh.empresa_id
                     AND con.tipo_recurso = 'CONDUCTOR'
                   WHERE veh.operacion_id = p_operacion_id
                     AND veh.tipo_recurso = 'VEHICULO'
                   ORDER BY veh.holgura_pax, con.horas_dia, veh.recurso_id, con.recurso_id
                   FETCH FIRST 1 ROWS ONLY) LOOP
            UPDATE OPERACION_TRANSPORTE
               SET empresa_id    = r.empresa_id,
                   vehiculo_id   = r.vehiculo_id,
                   conductor_id  = r.conductor_id,
                   estado_actual = 'ASIGNADO'
             WHERE operacion_id = p_operacion_id;
            RETURN;
        END LOOP;

        RAISE_APPLICATION_ERROR(-20101,
            'No hay vehículo y conductor elegibles de una misma empresa para ' || v_codigo);
    END asignar_automatico;

    FUNCTION faltante_transporte (p_salida_id NUMBER, p_pasajeros NUMBER,
                                  p_operacion_id NUMBER DEFAULT NULL) RETURN VARCHAR2 IS
    BEGIN
        IF p_salida_id IS NULL OR NVL(p_pasajeros, 0) <= 0 THEN
            RETURN NULL;
        END IF;

        FOR t IN (SELECT lo.nombre AS origen,
                         ld.nombre AS destino,
                         o.hora_programada_salida AS hora,
                         NVL(SUM(v.capacidad_pax), 0) AS capacidad   -- sin vehículo = 0
                    FROM OPERACION_TRANSPORTE o
                    JOIN DOMINIO_ESTADOS e ON e.codigo_estado = o.estado_actual
                    JOIN LUGARES lo ON lo.lugar_id = o.origen_id
                    JOIN LUGARES ld ON ld.lugar_id = o.destino_id
                    LEFT JOIN VEHICULO v ON v.vehiculo_id = o.vehiculo_id
                   WHERE o.salida_id = p_salida_id
                     AND e.ocupa_recursos = 'S'                         -- ignora CANCELADO
                     AND (p_operacion_id IS NULL
                          OR (o.origen_id, o.destino_id, o.hora_programada_salida) IN
                             (SELECT x.origen_id, x.destino_id, x.hora_programada_salida
                                FROM OPERACION_TRANSPORTE x
                               WHERE x.operacion_id = p_operacion_id))
                   GROUP BY o.origen_id, o.destino_id, lo.nombre, ld.nombre, o.hora_programada_salida
                  HAVING NVL(SUM(v.capacidad_pax), 0) < p_pasajeros
                   ORDER BY o.hora_programada_salida) LOOP
            RETURN 'tramo ' || t.origen || ' -> ' || t.destino
                   || ' (' || TO_CHAR(t.hora, 'DD/MM/YYYY HH24:MI') || '): capacidad '
                   || t.capacidad || ' < ' || p_pasajeros || ' pasajeros';
        END LOOP;
        RETURN NULL;
    END faltante_transporte;

END PKG_ASIGNACION;
