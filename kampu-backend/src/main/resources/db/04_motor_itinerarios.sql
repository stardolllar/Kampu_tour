-- =====================================================================
-- KAMPU / TOUR MANAGER - MOTOR DE ITINERARIOS (Itinerary Engine, estilo FIDS)
-- Ejecutar DESPUÉS de 01_schema_v4.sql, 02_data.sql y 03_particionamiento_roles.sql,
-- con el usuario dueño del esquema.
--
-- Modelo Master-Detail (no modifica ninguna tabla existente):
--   RESERVAS_MASTER      1 a 1 con RESERVAS: estado logístico del paquete vendido,
--                        hotel del pasajero y aeropuerto de llegada.
--   BOLETOS_AEREOS       vuelo comprado por fuera (LATAM / Sky / JetSMART) y cargado
--                        a mano por Ventas: PNR, aerolínea, horas y PDF del boarding pass.
--   SEGMENTOS_OPERATIVOS tareas de campo de la reserva: TRANSFER_IN, TOUR_DIARIO,
--                        TRANSFER_OUT, ALOJAMIENTO. El Admin las consolida entre reservas
--                        (grupo_codigo) y les asigna vehículo y operador.
--
-- Sin triggers, vistas ni procedimientos nuevos: las reglas viven en el backend
-- (pe.edu.upeu.lp2_gp2.itinerario).
-- =====================================================================

CREATE TABLE RESERVAS_MASTER (
    reserva_id        NUMBER PRIMARY KEY,
    estado_logistico  VARCHAR2(30) DEFAULT 'VUELO_PENDIENTE' NOT NULL,
    hotel_id          NUMBER NOT NULL,
    aeropuerto_id     NUMBER NOT NULL,
    creado_por        VARCHAR2(100),
    fecha_creacion    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    actualizado_en    TIMESTAMP,
    CONSTRAINT fk_rm_reserva    FOREIGN KEY (reserva_id)    REFERENCES RESERVAS(reserva_id),
    CONSTRAINT fk_rm_hotel      FOREIGN KEY (hotel_id)      REFERENCES LUGARES(lugar_id),
    CONSTRAINT fk_rm_aeropuerto FOREIGN KEY (aeropuerto_id) REFERENCES LUGARES(lugar_id),
    CONSTRAINT chk_rm_estado CHECK (estado_logistico IN
        ('VUELO_PENDIENTE', 'CONFIRMADO_CON_VUELO', 'EN_CURSO', 'FINALIZADO', 'CANCELADO'))
);

CREATE TABLE BOLETOS_AEREOS (
    boleto_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id         NUMBER       NOT NULL,
    tipo_vuelo         VARCHAR2(10) NOT NULL,
    aerolinea          VARCHAR2(20) NOT NULL,
    numero_vuelo       VARCHAR2(10) NOT NULL,
    codigo_pnr         VARCHAR2(6)  NOT NULL,
    aeropuerto_origen  CHAR(3)      NOT NULL,
    aeropuerto_destino CHAR(3)      NOT NULL,
    fecha_hora_salida  TIMESTAMP    NOT NULL,
    fecha_hora_llegada TIMESTAMP    NOT NULL,
    archivo_pdf        VARCHAR2(300),
    nombre_archivo     VARCHAR2(200),
    tamanio_bytes      NUMBER,
    registrado_por     VARCHAR2(100),
    fecha_registro     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_ba_master  FOREIGN KEY (reserva_id) REFERENCES RESERVAS_MASTER(reserva_id),
    CONSTRAINT uq_ba_tipo    UNIQUE (reserva_id, tipo_vuelo),
    CONSTRAINT chk_ba_tipo   CHECK (tipo_vuelo IN ('LLEGADA', 'SALIDA')),
    CONSTRAINT chk_ba_linea  CHECK (aerolinea IN ('LATAM', 'SKY', 'JETSMART', 'OTRA')),
    CONSTRAINT chk_ba_pnr    CHECK (REGEXP_LIKE(codigo_pnr, '^[A-Z0-9]{6}$')),
    CONSTRAINT chk_ba_iata   CHECK (REGEXP_LIKE(aeropuerto_origen, '^[A-Z]{3}$') AND REGEXP_LIKE(aeropuerto_destino, '^[A-Z]{3}$')),
    CONSTRAINT chk_ba_horas  CHECK (fecha_hora_llegada > fecha_hora_salida)
);

CREATE TABLE SEGMENTOS_OPERATIVOS (
    segmento_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id            NUMBER       NOT NULL,
    tipo                  VARCHAR2(20) NOT NULL,
    fecha                 DATE         NOT NULL,
    hora_inicio           TIMESTAMP    NOT NULL,
    origen_id             NUMBER       NOT NULL,
    destino_id            NUMBER       NOT NULL,
    pax                   NUMBER(3)    NOT NULL,
    boleto_id             NUMBER,
    vehiculo_id           NUMBER,
    operador_id           NUMBER,
    grupo_codigo          VARCHAR2(30),
    estado                VARCHAR2(30) DEFAULT 'PROGRAMADO' NOT NULL,
    estado_actualizado_en TIMESTAMP,
    observacion           VARCHAR2(200),
    version               NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT fk_so_master    FOREIGN KEY (reserva_id)  REFERENCES RESERVAS_MASTER(reserva_id),
    CONSTRAINT fk_so_origen    FOREIGN KEY (origen_id)   REFERENCES LUGARES(lugar_id),
    CONSTRAINT fk_so_destino   FOREIGN KEY (destino_id)  REFERENCES LUGARES(lugar_id),
    CONSTRAINT fk_so_boleto    FOREIGN KEY (boleto_id)   REFERENCES BOLETOS_AEREOS(boleto_id),
    CONSTRAINT fk_so_vehiculo  FOREIGN KEY (vehiculo_id) REFERENCES VEHICULOS(vehiculo_id),
    CONSTRAINT fk_so_operador  FOREIGN KEY (operador_id) REFERENCES USUARIOS_SISTEMA(usuario_id),
    CONSTRAINT uq_so_tarea     UNIQUE (reserva_id, tipo, fecha),
    CONSTRAINT chk_so_tipo     CHECK (tipo IN ('TRANSFER_IN', 'TOUR_DIARIO', 'TRANSFER_OUT', 'ALOJAMIENTO')),
    CONSTRAINT chk_so_pax      CHECK (pax BETWEEN 1 AND 999),
    CONSTRAINT chk_so_asignado CHECK ((vehiculo_id IS NULL AND operador_id IS NULL AND grupo_codigo IS NULL)
                                   OR (vehiculo_id IS NOT NULL AND operador_id IS NOT NULL AND grupo_codigo IS NOT NULL)),
    CONSTRAINT chk_so_estado   CHECK (estado IN ('PROGRAMADO',
        'EN_AEROPUERTO', 'PASAJERO_ABORDADO', 'EN_TRANSITO_A_HOTEL', 'DEJADO_EN_HOTEL',
        'RECOGIENDO_HOTEL', 'RUMBO_AL_DESTINO', 'EN_ATRACTIVO', 'RETORNANDO', 'FINALIZADO_EN_HOTEL',
        'EN_TRANSITO_A_AEROPUERTO', 'DEJADO_EN_AEROPUERTO'))
);
-- Panel FIDS (por fecha y tipo), jornada del operador y viajes consolidados
CREATE INDEX idx_so_fecha_tipo ON SEGMENTOS_OPERATIVOS (fecha, tipo);
CREATE INDEX idx_so_operador   ON SEGMENTOS_OPERATIVOS (operador_id, fecha);
CREATE INDEX idx_so_grupo      ON SEGMENTOS_OPERATIVOS (grupo_codigo);

