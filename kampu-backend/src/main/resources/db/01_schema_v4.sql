-- =====================================================================
-- KAMPU / TOUR MANAGER - SCRIPT v4 (Oracle 12.2+)
-- Ejecutar en SQL Developer como script (F5) con el usuario dueño.
--
-- Base: las 14 tablas del modelo v4 + AUDITORIA (la exige el trigger de
-- auditoría). Columnas marcadas "-- (+v4)" se agregaron al modelo v4 para
-- no perder funciones que la aplicación ya tenía (imagen del paquete,
-- moneda y aprobación de pagos, coordenadas para calcular duraciones...).
--
-- Objetos de backend: exactamente 2 por categoría
--   PL/SQL    FN_ESTADO_PAGO_PAQUETE, SP_REGISTRAR_CLIENTE_EXTERNO
--   Paquetes  PKG_SEGURIDAD_ROLES, PKG_GESTION_PAQUETES_CLIENTE
--   Vistas    VW_PAQUETES_CLIENTE, VW_RESUMEN_PAQUETES_POR_ROL
--   Triggers  TRG_AUDITORIA_ESTADO_PAQUETE, TRG_VALIDAR_PAGO_PAQUETE
-- El resto de reglas (cupos, transiciones de tráfico, asignación de
-- recursos) vive en el backend Spring Boot.
--
-- Particionamiento y roles de base de datos: 03_particionamiento_roles.sql
-- =====================================================================

-- =====================================================================
-- 1. TABLAS
-- =====================================================================

-- 1. USUARIOS DEL SISTEMA (personal interno: Admin, Ventas, Operador)
CREATE TABLE USUARIOS_SISTEMA (
    usuario_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR2(50)  NOT NULL UNIQUE,
    password_hash VARCHAR2(255) NOT NULL,
    rol           VARCHAR2(50)  NOT NULL,
    estado        VARCHAR2(20)  DEFAULT 'ACTIVO',
    CONSTRAINT chk_usu_rol    CHECK (rol IN ('ADMIN', 'VENDEDOR', 'OPERADOR')),
    CONSTRAINT chk_usu_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

-- 2. CLIENTES (turistas; con password_hash pueden entrar al portal web)
CREATE TABLE CLIENTES (
    cliente_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo  VARCHAR2(150) NOT NULL,
    tipo_documento   VARCHAR2(20)  NOT NULL,
    numero_documento VARCHAR2(20)  NOT NULL,
    email            VARCHAR2(100) NOT NULL,
    telefono         VARCHAR2(20)  NOT NULL,
    password_hash    VARCHAR2(255),                         -- NULL: cliente creado por Ventas, sin cuenta web
    fecha_registro   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    estado_cuenta    VARCHAR2(20) DEFAULT 'ACTIVO',
    CONSTRAINT chk_cli_tipo_doc CHECK (tipo_documento IN ('DNI', 'CE', 'PASAPORTE', 'RUC')),
    CONSTRAINT chk_cli_cuenta   CHECK (estado_cuenta IN ('ACTIVO', 'INACTIVO', 'BLOQUEADO')),   -- (+v4)
    CONSTRAINT uq_cli_tipo_doc  UNIQUE (tipo_documento, numero_documento)
);
-- Correo, documento y teléfono no se repiten (teléfono: solo dígitos)   (+v4)
CREATE UNIQUE INDEX uq_cli_email       ON CLIENTES (LOWER(email));
CREATE UNIQUE INDEX uq_cli_numero_doc  ON CLIENTES (UPPER(numero_documento));
CREATE UNIQUE INDEX uq_cli_telefono    ON CLIENTES (TRANSLATE(telefono, '0+-() ', '0'));

-- 3. PROVEEDORES (propios y terceros: Kampu Tours es el único con es_propio = 1)
CREATE TABLE PROVEEDORES (
    proveedor_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_comercial VARCHAR2(150) NOT NULL,
    ruc              CHAR(11) NOT NULL UNIQUE,
    telefono         VARCHAR2(20),
    es_propio        NUMBER(1) DEFAULT 0 NOT NULL,          -- 1: Kampu Tours, 0: tercero
    estado           VARCHAR2(20) DEFAULT 'ACTIVO',
    CONSTRAINT chk_prov_propio CHECK (es_propio IN (0, 1)),
    CONSTRAINT chk_prov_estado CHECK (estado IN ('ACTIVO', 'INACTIVO', 'SUSPENDIDO')),
    CONSTRAINT chk_prov_ruc    CHECK (REGEXP_LIKE(ruc, '^(10|15|17|20)[0-9]{9}$'))       -- (+v4)
);
-- Un solo proveedor propio (no depende de que sea el ID 1)   (+v4)
CREATE UNIQUE INDEX uq_prov_propio   ON PROVEEDORES (CASE WHEN es_propio = 1 THEN 1 END);
CREATE UNIQUE INDEX uq_prov_telefono ON PROVEEDORES (TRANSLATE(telefono, '0+-() ', '0'));

-- 4. LUGARES (orígenes y destinos)
CREATE TABLE LUGARES (
    lugar_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR2(150) NOT NULL,
    tipo_lugar VARCHAR2(20)  NOT NULL,
    ciudad     VARCHAR2(100) NOT NULL,
    latitud    NUMBER(9,6),                                 -- (+v4) para calcular duraciones reales
    longitud   NUMBER(9,6),                                 -- (+v4)
    CONSTRAINT chk_lug_tipo   CHECK (tipo_lugar IN ('AEROPUERTO', 'TERMINAL', 'HOTEL', 'ATRACTIVO', 'CIUDAD', 'OTRO')),
    CONSTRAINT chk_lug_coords CHECK ((latitud IS NULL AND longitud IS NULL)
                                     OR (latitud BETWEEN -90 AND 90 AND longitud BETWEEN -180 AND 180))
);

-- 5. PERSONAL (guías y conductores, propios o de un proveedor)
CREATE TABLE PERSONAL (
    personal_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor_id     NUMBER NOT NULL,
    nombre_completo  VARCHAR2(150) NOT NULL,
    rol              VARCHAR2(20) NOT NULL,                 -- 'GUIA', 'CONDUCTOR', 'AMBOS'
    telefono         VARCHAR2(20),                          -- (+v4)
    num_licencia     VARCHAR2(20),
    cat_licencia     VARCHAR2(10),
    venc_licencia    DATE,
    estado           VARCHAR2(20) DEFAULT 'DISPONIBLE',
    CONSTRAINT fk_pers_prov    FOREIGN KEY (proveedor_id) REFERENCES PROVEEDORES(proveedor_id),
    CONSTRAINT chk_pers_rol    CHECK (rol IN ('GUIA', 'CONDUCTOR', 'AMBOS')),
    CONSTRAINT chk_pers_est    CHECK (estado IN ('DISPONIBLE', 'OCUPADO', 'INACTIVO')),
    -- Quien conduce necesita licencia completa   (+v4)
    CONSTRAINT chk_pers_licencia CHECK (rol = 'GUIA'
        OR (num_licencia IS NOT NULL AND cat_licencia IS NOT NULL AND venc_licencia IS NOT NULL)),
    CONSTRAINT chk_pers_cat    CHECK (cat_licencia IS NULL OR cat_licencia IN ('A-I', 'A-IIa', 'A-IIb', 'A-IIIa', 'A-IIIb', 'A-IIIc')),
    CONSTRAINT uq_pers_licencia UNIQUE (num_licencia)
);
CREATE UNIQUE INDEX uq_pers_telefono ON PERSONAL (TRANSLATE(telefono, '0+-() ', '0'));
CREATE INDEX idx_pers_proveedor ON PERSONAL (proveedor_id);

-- 6. VEHICULOS
CREATE TABLE VEHICULOS (
    vehiculo_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor_id       NUMBER NOT NULL,
    placa              VARCHAR2(10) NOT NULL UNIQUE,
    tipo_vehiculo      VARCHAR2(20) NOT NULL,
    marca_modelo       VARCHAR2(100),                       -- (+v4)
    capacidad_pax      NUMBER(3) NOT NULL,
    prox_mantenimiento DATE,
    estado             VARCHAR2(20) DEFAULT 'OPERATIVO',
    CONSTRAINT fk_veh_prov  FOREIGN KEY (proveedor_id) REFERENCES PROVEEDORES(proveedor_id),
    CONSTRAINT chk_veh_est  CHECK (estado IN ('OPERATIVO', 'MANTENIMIENTO', 'INACTIVO')),
    CONSTRAINT chk_veh_tipo CHECK (tipo_vehiculo IN ('AUTO', 'CAMIONETA_4X4', 'VAN', 'MINIBUS', 'BUS')),   -- (+v4)
    CONSTRAINT chk_veh_cap  CHECK (capacidad_pax > 0)                                                  -- (+v4)
);
CREATE INDEX idx_veh_proveedor ON VEHICULOS (proveedor_id);

-- 7. PAQUETES TOUR
CREATE TABLE PAQUETES_TOUR (
    paquete_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR2(100) NOT NULL,
    descripcion VARCHAR2(1000),                             -- (+v4) catálogo y web
    precio_base NUMBER(10,2) NOT NULL,
    dias        NUMBER(2) NOT NULL,
    noches      NUMBER(2) NOT NULL,
    imagen      VARCHAR2(500),                              -- (+v4) catálogo y web
    estado      VARCHAR2(20) DEFAULT 'ACTIVO',
    CONSTRAINT chk_paq_precio CHECK (precio_base > 0),                                   -- (+v4)
    CONSTRAINT chk_paq_dias   CHECK (dias > 0 AND noches >= 0 AND noches <= dias),       -- (+v4)
    CONSTRAINT chk_paq_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))                   -- (+v4)
);

-- 8. SALIDAS PROGRAMADAS (fecha_fin y cupos los calcula el backend)
CREATE TABLE SALIDAS_PROGRAMADAS (
    salida_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paquete_id        NUMBER NOT NULL,
    guia_id           NUMBER,                               -- PERSONAL con rol GUIA o AMBOS
    fecha_inicio      DATE NOT NULL,
    fecha_fin         DATE NOT NULL,
    cupos_maximos     NUMBER(3) NOT NULL,
    cupos_disponibles NUMBER(3) NOT NULL,
    estado            VARCHAR2(20) DEFAULT 'PROGRAMADA',
    CONSTRAINT fk_sal_paq    FOREIGN KEY (paquete_id) REFERENCES PAQUETES_TOUR(paquete_id),
    CONSTRAINT fk_sal_guia   FOREIGN KEY (guia_id) REFERENCES PERSONAL(personal_id),
    CONSTRAINT chk_sal_est   CHECK (estado IN ('PROGRAMADA', 'CONFIRMADA', 'COMPLETADA', 'CANCELADA')),
    CONSTRAINT chk_sal_fechas CHECK (fecha_fin >= fecha_inicio),                                       -- (+v4)
    CONSTRAINT chk_sal_cupos CHECK (cupos_maximos > 0 AND cupos_disponibles BETWEEN 0 AND cupos_maximos) -- (+v4)
);
CREATE INDEX idx_sal_paquete ON SALIDAS_PROGRAMADAS (paquete_id);
CREATE INDEX idx_sal_guia    ON SALIDAS_PROGRAMADAS (guia_id);

-- 9. RESERVAS
CREATE TABLE RESERVAS (
    reserva_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id         NUMBER NOT NULL,
    fecha_reserva      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    monto_total        NUMBER(10,2) DEFAULT 0 NOT NULL,
    monto_pagado       NUMBER(10,2) DEFAULT 0 NOT NULL,
    estado_reserva     VARCHAR2(20) DEFAULT 'PENDIENTE',
    estado_pago        VARCHAR2(20) DEFAULT 'PENDIENTE',
    observaciones      VARCHAR2(200),                       -- (+v4)
    forma_reembolso    VARCHAR2(50),                        -- (+v4) anulación con devolución
    usuario_anula_id   NUMBER,                              -- (+v4)
    boleta_enviada_en  TIMESTAMP,                           -- (+v4) boleta por correo
    CONSTRAINT fk_res_cli     FOREIGN KEY (cliente_id) REFERENCES CLIENTES(cliente_id),
    CONSTRAINT fk_res_usuario FOREIGN KEY (usuario_anula_id) REFERENCES USUARIOS_SISTEMA(usuario_id),  -- (+v4)
    CONSTRAINT chk_res_est    CHECK (estado_reserva IN ('PENDIENTE', 'CONFIRMADA', 'ANULADA', 'COMPLETADA')),
    CONSTRAINT chk_pago_est   CHECK (estado_pago IN ('PENDIENTE', 'PARCIAL', 'PAGADO', 'REEMBOLSADO')),
    CONSTRAINT chk_res_montos CHECK (monto_total >= 0 AND monto_pagado BETWEEN 0 AND monto_total)    -- (+v4)
);
CREATE INDEX idx_res_cliente ON RESERVAS (cliente_id);

-- 10. DETALLE RESERVA
CREATE TABLE DETALLE_RESERVA (
    detalle_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id      NUMBER NOT NULL,
    salida_id       NUMBER NOT NULL,
    cantidad        NUMBER(2) NOT NULL,
    precio_unitario NUMBER(10,2) NOT NULL,
    descuento       NUMBER(10,2) DEFAULT 0 NOT NULL,
    subtotal        NUMBER(10,2) GENERATED ALWAYS AS (cantidad * precio_unitario - descuento) VIRTUAL,
    CONSTRAINT fk_det_res FOREIGN KEY (reserva_id) REFERENCES RESERVAS(reserva_id),
    CONSTRAINT fk_det_sal FOREIGN KEY (salida_id) REFERENCES SALIDAS_PROGRAMADAS(salida_id),
    CONSTRAINT chk_det_cantidad CHECK (cantidad > 0),                                   -- (+v4)
    CONSTRAINT uq_det_reserva_salida UNIQUE (reserva_id, salida_id)                     -- (+v4)
);
CREATE INDEX idx_det_salida ON DETALLE_RESERVA (salida_id);

-- 11. PASAJEROS
CREATE TABLE PASAJEROS_RESERVA (
    pasajero_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    detalle_id       NUMBER NOT NULL,
    nombre_completo  VARCHAR2(150) NOT NULL,
    tipo_documento   VARCHAR2(20)  NOT NULL,
    numero_documento VARCHAR2(20)  NOT NULL,
    nacionalidad     VARCHAR2(50),                          -- (+v4)
    fecha_nacimiento DATE,                                  -- (+v4)
    CONSTRAINT fk_pas_det FOREIGN KEY (detalle_id) REFERENCES DETALLE_RESERVA(detalle_id),
    CONSTRAINT chk_pas_tipo_doc CHECK (tipo_documento IN ('DNI', 'CE', 'PASAPORTE')),  -- (+v4)
    CONSTRAINT uq_pas_detalle_doc UNIQUE (detalle_id, tipo_documento, numero_documento) -- (+v4)
);

-- 12. PAGOS (registrado_por: quién lo registró; es la clave de partición)
CREATE TABLE PAGOS (
    pago_id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id         NUMBER NOT NULL,
    monto              NUMBER(10,2) NOT NULL,
    moneda             VARCHAR2(10) DEFAULT 'PEN' NOT NULL,                          -- (+v4)
    tipo_cambio        NUMBER(8,4) DEFAULT 1 NOT NULL,                               -- (+v4)
    monto_pen          NUMBER(10,2) GENERATED ALWAYS AS (ROUND(monto * tipo_cambio, 2)) VIRTUAL,  -- (+v4)
    metodo_pago        VARCHAR2(50),
    codigo_transaccion VARCHAR2(100),
    fecha_pago         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    estado_transaccion VARCHAR2(20) DEFAULT 'APROBADO' NOT NULL,                     -- (+v4)
    registrado_por     VARCHAR2(20) DEFAULT 'VENDEDOR' NOT NULL,                     -- (+v4)
    CONSTRAINT fk_pag_res    FOREIGN KEY (reserva_id) REFERENCES RESERVAS(reserva_id),
    CONSTRAINT chk_pag_monto CHECK (monto > 0),
    CONSTRAINT chk_pag_moneda CHECK (moneda IN ('PEN', 'USD', 'EUR')),
    CONSTRAINT chk_pag_tc    CHECK (tipo_cambio > 0 AND (moneda <> 'PEN' OR tipo_cambio = 1)),
    CONSTRAINT chk_pag_estado CHECK (estado_transaccion IN ('PENDIENTE', 'APROBADO', 'RECHAZADO', 'REEMBOLSADO')),
    CONSTRAINT chk_pag_origen CHECK (registrado_por IN ('ADMIN', 'VENDEDOR', 'CLIENTE'))
);
CREATE INDEX idx_pag_reserva ON PAGOS (reserva_id);

-- 13. OPERACIONES DE TRANSPORTE (tráfico; transiciones y validaciones en el backend)
-- Código de operación KMP-001, KMP-002...
CREATE SEQUENCE SEQ_CODIGO_OPERACION START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE OPERACIONES_TRANSPORTE (
    operacion_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_operacion VARCHAR2(20) UNIQUE NOT NULL,
    salida_id        NUMBER,                                -- NULL: traslado suelto
    origen_id        NUMBER NOT NULL,
    destino_id       NUMBER NOT NULL,
    vehiculo_id      NUMBER,
    conductor_id     NUMBER,
    pax_programados  NUMBER(3) NOT NULL,
    hora_salida      TIMESTAMP NOT NULL,
    hora_llegada     TIMESTAMP NOT NULL,                    -- la calcula el backend (OSRM / coordenadas)
    estado           VARCHAR2(20) DEFAULT 'PROGRAMADO',
    observaciones    VARCHAR2(200),                         -- (+v4)
    CONSTRAINT fk_op_sal     FOREIGN KEY (salida_id) REFERENCES SALIDAS_PROGRAMADAS(salida_id),
    CONSTRAINT fk_op_veh     FOREIGN KEY (vehiculo_id) REFERENCES VEHICULOS(vehiculo_id),
    CONSTRAINT fk_op_con     FOREIGN KEY (conductor_id) REFERENCES PERSONAL(personal_id),
    CONSTRAINT fk_op_origen  FOREIGN KEY (origen_id) REFERENCES LUGARES(lugar_id),     -- (+v4)
    CONSTRAINT fk_op_destino FOREIGN KEY (destino_id) REFERENCES LUGARES(lugar_id),    -- (+v4)
    CONSTRAINT chk_op_est    CHECK (estado IN ('PROGRAMADO', 'ASIGNADO', 'EMBARQUE', 'EN_RUTA', 'FINALIZADO', 'CANCELADO')),
    CONSTRAINT chk_op_od     CHECK (origen_id <> destino_id),                          -- (+v4)
    CONSTRAINT chk_op_pax    CHECK (pax_programados > 0),                              -- (+v4)
    CONSTRAINT chk_op_horas  CHECK (hora_llegada > hora_salida)                        -- (+v4)
);
CREATE INDEX idx_op_salida    ON OPERACIONES_TRANSPORTE (salida_id);
CREATE INDEX idx_op_vehiculo  ON OPERACIONES_TRANSPORTE (vehiculo_id, hora_salida);
CREATE INDEX idx_op_conductor ON OPERACIONES_TRANSPORTE (conductor_id, hora_salida);

