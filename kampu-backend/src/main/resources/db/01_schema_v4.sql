-- 7.1 TRG_AUDITORIA_ESTADO_PAQUETE (1/2)
--     Cada cambio del estado de ejecución (estado_reserva) o del estado de
--     pago de un paquete queda en AUDITORIA con usuario, rol y valores.
CREATE OR REPLACE TRIGGER TRG_AUDITORIA_ESTADO_PAQUETE
AFTER UPDATE OF estado_reserva, estado_pago ON RESERVAS
FOR EACH ROW
DECLARE
    v_usuario VARCHAR2(100) := PKG_SEGURIDAD_ROLES.usuario_actual();
    v_rol     VARCHAR2(20)  := NVL(PKG_SEGURIDAD_ROLES.rol_actual(), 'SISTEMA');
BEGIN
    IF v_rol NOT IN ('ADMIN', 'VENDEDOR', 'OPERADOR', 'CLIENTE') THEN
        v_rol := 'SISTEMA';
    END IF;
    IF NVL(:OLD.estado_reserva, '-') <> NVL(:NEW.estado_reserva, '-') THEN
        INSERT INTO AUDITORIA (accion, entidad, entidad_id, campo, valor_anterior, valor_nuevo, detalle, usuario, rol_usuario)
        VALUES ('ACTUALIZAR', 'RESERVA', :NEW.reserva_id, 'ESTADO_RESERVA', :OLD.estado_reserva, :NEW.estado_reserva,
                'Estado de ejecución del paquete', v_usuario, v_rol);
    END IF;
    IF NVL(:OLD.estado_pago, '-') <> NVL(:NEW.estado_pago, '-') THEN
        INSERT INTO AUDITORIA (accion, entidad, entidad_id, campo, valor_anterior, valor_nuevo, detalle, usuario, rol_usuario)
        VALUES ('ACTUALIZAR', 'RESERVA', :NEW.reserva_id, 'ESTADO_PAGO', :OLD.estado_pago, :NEW.estado_pago,
                'Estado de pago del paquete', v_usuario, v_rol);
    END IF;
END;
